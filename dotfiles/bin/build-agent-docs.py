#!/usr/bin/env python3
"""Assemble the per-tool agent instruction files from the shared rule canon.

Codex reads ``~/.codex/AGENTS.md`` and Claude Code reads ``~/.claude/CLAUDE.md``.
Neither supports including another file at load time, so the shared rules have
to be physically present in both. Keeping one canon under ``agent-rules/`` and
generating both files is what stops the two from drifting apart, which is how
they got out of sync before.

Usage:
    build-agent-docs.py            # write the generated files
    build-agent-docs.py --check    # fail if the committed files are stale
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

DOTFILES = Path(__file__).resolve().parent.parent
RULES_DIR = DOTFILES / "agent-rules"
ADAPTERS_DIR = RULES_DIR / "adapters"

BANNER = (
    "<!-- Generated by dotfiles/bin/build-agent-docs.py from"
    " dotfiles/agent-rules/.\n"
    "     Edit the sources there and run dotfiles/bin/install-agent-config.sh.\n"
    "     Do not edit this file directly; it is overwritten. -->"
)

TARGETS = {
    "codex": (ADAPTERS_DIR / "codex-header.md", DOTFILES / "codex" / "AGENTS.md"),
    "claude": (ADAPTERS_DIR / "claude-header.md", DOTFILES / "claude" / "CLAUDE.md"),
}


def shared_sections() -> list[Path]:
    """Canon files in load order. Numeric prefixes define that order.

    Dot-prefixed entries are skipped: copying this tree off macOS leaves
    AppleDouble ``._name.md`` siblings that match the glob and are not text.
    """
    sections = sorted(
        p for p in RULES_DIR.glob("*.md") if p.is_file() and not p.name.startswith(".")
    )
    if not sections:
        raise SystemExit(f"no rule sections found in {RULES_DIR}")
    return sections


def render(header: Path) -> str:
    parts = [BANNER, header.read_text(encoding="utf-8").strip()]
    parts.extend(p.read_text(encoding="utf-8").strip() for p in shared_sections())
    return "\n\n".join(parts) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed files match the canon instead of writing them",
    )
    args = parser.parse_args()

    stale: list[str] = []
    for name, (header, output) in sorted(TARGETS.items()):
        rendered = render(header)
        if args.check:
            current = output.read_text(encoding="utf-8") if output.exists() else ""
            if current != rendered:
                stale.append(f"{output.relative_to(DOTFILES.parent)} ({name})")
            continue
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(rendered, encoding="utf-8")
        print(f"wrote {output.relative_to(DOTFILES.parent)}")

    if stale:
        print(
            "Generated agent docs are stale: "
            + ", ".join(stale)
            + "\nRun dotfiles/bin/build-agent-docs.py and commit the result.",
            file=sys.stderr,
        )
        return 1
    if args.check:
        print("Generated agent docs match the canon.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
